#!/usr/bin/env node
// Writes docs/demo-data.js, the recording the site's first Claude Code demo
// replays, so the demo cannot drift from what the plugin really produces.
//
//   node scripts/build-demo.mjs [evals/results/<file>.json]
//       a passing ratelimit-live result that has a transcript and a report
//       (the latest results file with one when no file is given)
//   node scripts/build-demo.mjs --jsonl <run.jsonl> --cwd <session dir> [--prompt <text>]
//       straight from a raw stream-json recording
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildTranscript, scrub } from '../evals/transcript.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const resultsDir = join(root, 'evals', 'results')
const SCENARIO = 'ratelimit-live'

const args = process.argv.slice(2)
const opt = name => {
  const i = args.indexOf(`--${name}`)
  return i === -1 ? undefined : args[i + 1]
}
const fail = msg => { console.error(`build-demo: ${msg}`); process.exit(1) }

// Scrubs every string in the report, so no path from the session survives.
const cleanReport = (value, cwd) =>
  typeof value === 'string' ? scrub(value, cwd)
    : Array.isArray(value) ? value.map(v => cleanReport(v, cwd))
      : value && typeof value === 'object' ? Object.fromEntries(Object.entries(value).map(([k, v]) => [k, cleanReport(v, cwd)]))
        : value

function fromJsonl(file) {
  const cwd = opt('cwd')
  if (!cwd) fail('--jsonl needs --cwd <the directory the session ran in>')
  const stream = readFileSync(file, 'utf8')
  const prompt = opt('prompt') ?? JSON.parse(readFileSync(join(resultsDir, '..', 'scenarios', SCENARIO, 'scenario.json'), 'utf8')).prompt
  const events = stream.split('\n').flatMap(l => { try { return [JSON.parse(l)] } catch { return [] } })
  const report = events.filter(e => e.type === 'assistant').flatMap(e => e.message?.content ?? [])
    .filter(b => b.type === 'tool_use' && b.name === 'mcp__whiteboard-defense__report').map(b => b.input).at(-1)
  if (!report) fail(`no report tool call in ${file}`)
  return {
    recordedAt: events.find(e => e.timestamp)?.timestamp ?? statSync(file).mtime.toISOString(),
    model: events.find(e => e.type === 'system' && e.model)?.model ?? events.find(e => e.type === 'assistant')?.message?.model,
    transcript: buildTranscript(stream, { cwd, prompt }),
    report: cleanReport(report, cwd),
    cwd,
  }
}

function fromResults(file) {
  const data = JSON.parse(readFileSync(file, 'utf8'))
  const hit = (data.results ?? []).find(r => r.scenario === SCENARIO && r.pass && r.report && r.transcript?.length)
  if (!hit) return null
  // The file name is the run's ISO time with ":" and "." turned into "-".
  const stamp = file.match(/(\d{4}-\d\d-\d\dT)(\d\d)-(\d\d)-(\d\d)-(\d+)Z\.json$/)
  return {
    recordedAt: stamp ? `${stamp[1]}${stamp[2]}:${stamp[3]}:${stamp[4]}.${stamp[5]}Z` : statSync(file).mtime.toISOString(),
    model: data.model,
    transcript: hit.transcript,
    report: cleanReport(hit.report, hit.cwd),
    cwd: hit.cwd,
  }
}

let built = null
if (opt('jsonl')) built = fromJsonl(resolve(opt('jsonl')))
else {
  const given = args.find(a => !a.startsWith('--'))
  const files = given ? [resolve(given)] : readdirSync(resultsDir).filter(f => f.endsWith('.json')).sort().reverse().map(f => join(resultsDir, f))
  for (const f of files) { built = fromResults(f); if (built) { console.log(`using ${f}`); break } }
  if (!built) fail(`no passing ${SCENARIO} result with a transcript and a report in ${given ?? resultsDir}. Run the eval (node evals/run.mjs --only ${SCENARIO}) first, or build from a raw recording with --jsonl <file> --cwd <dir>.`)
}

const { cwd, ...demo } = built
const out = join(root, 'docs', 'demo-data.js')
writeFileSync(out, `// Generated by scripts/build-demo.mjs from a recorded run. Do not edit by hand.\nwindow.WB_DEMO = ${JSON.stringify({ ...demo, scenario: SCENARIO }, null, 2)}\n`)
console.log(`wrote ${out} (${demo.transcript.length} rows, model ${demo.model}, recorded ${demo.recordedAt})`)
