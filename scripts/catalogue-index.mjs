#!/usr/bin/env node
// Regenerates the catalogue index inside SKILL.md from defaults-catalogue.md,
// so the agent always has every entry in front of it without opening a file.
//
//   node scripts/catalogue-index.mjs          rewrite the index
//   node scripts/catalogue-index.mjs --check  exit 1 if the index is stale
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const skillDir = join(root, 'plugins/whiteboard-defense/skills/whiteboard')
const catalogue = readFileSync(join(skillDir, 'references/defaults-catalogue.md'), 'utf8')
const skillPath = join(skillDir, 'SKILL.md')
const skill = readFileSync(skillPath, 'utf8')

const START = '<!-- catalogue-index:start (generated by scripts/catalogue-index.mjs; do not edit) -->'
const END = '<!-- catalogue-index:end -->'

const entries = []
for (const block of catalogue.split(/^### /m).slice(1)) {
  const head = block.match(/^(D-[A-Z]+-\d+): (.+)$/m)
  if (!head) continue
  const field = name => block.match(new RegExp(`^- \\*\\*${name}\\*\\*: (.+)$`, 'm'))?.[1].trim()
  const trigger = field('Trigger')
  const def = field('Default')
  if (!trigger || !def) throw new Error(`${head[1]} is missing Trigger or Default`)
  entries.push(`- **${head[1]}** ${head[2]}. When: ${trigger.replace(/\.$/, '')}. Pattern: ${def}`)
}

const index = `${START}\n${entries.join('\n')}\n${END}`
const pattern = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`)
if (!pattern.test(skill)) throw new Error('SKILL.md has no catalogue-index markers')
const next = skill.replace(pattern, index)

if (process.argv.includes('--check')) {
  if (next !== skill) {
    console.error('SKILL.md catalogue index is stale: run node scripts/catalogue-index.mjs')
    process.exit(1)
  }
  console.log(`catalogue index up to date (${entries.length} entries)`)
} else {
  writeFileSync(skillPath, next)
  console.log(`wrote ${entries.length} entries to SKILL.md`)
}
